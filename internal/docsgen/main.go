// Command docsgen keeps the command table in docs/cli.md in sync with the CLI's
// own command table (internal/cli/cli.go).
//
// It renders the table by calling the CLI the way a user would — `idea help
// --format=md` — capturing the stdout writer it is handed, and splices the
// result between the generated-block markers in docs/cli.md. Prose outside the
// markers is never touched.
//
//	go run ./internal/docsgen              # rewrite docs/cli.md
//	go run ./internal/docsgen -check       # fail if it is out of date
//	go run ./internal/docsgen -api-check   # fail if docs/openapi.yaml has drifted
//
// `make docs`, `make docs-check` and `make api-check` are the intended entry
// points; CI runs the latter two so neither a new command nor a new HTTP route
// can ship undocumented. The API half lives in apicheck.go.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/devarispbrown/idea-harness/internal/cli"
)

const (
	beginMarker = "<!-- BEGIN generated commands -->"
	endMarker   = "<!-- END generated commands -->"
	// generatedNote sits inside the block so a reader editing docs/cli.md by
	// hand is told where the text actually comes from.
	generatedNote = "<!-- Generated by `make docs` from internal/cli/cli.go — do not edit by hand. -->"
)

func main() {
	check := flag.Bool("check", false, "report drift and exit non-zero instead of rewriting the file")
	apiCheck := flag.Bool("api-check", false, "compare docs/openapi.yaml against the routes registered in internal/daemon and exit non-zero on drift")
	claimsCheck := flag.Bool("claims-check", false, "fail when a load-bearing security claim is stated outside its canonical document without a link")
	docsLint := flag.Bool("docs-lint", false, "check that every `idea ...` command in README and the quickstart names a real verb and a resolvable reference")
	apiDocs := flag.Bool("api-docs", false, "add a row to docs/api.md for every route that has none")
	apiDocsCheck := flag.Bool("api-docs-check", false, "fail if docs/api.md is missing a row for any route, or has one for a route that does not exist")
	specJSON := flag.String("spec-json", "", "write docs/openapi.yaml to this path as JSON (used by `make api-docs-dist`)")
	flag.Parse()

	if *specJSON != "" {
		if err := writeSpecJSON(*specJSON); err != nil {
			fmt.Fprintln(os.Stderr, "spec-json:", err)
			os.Exit(1)
		}
		return
	}

	if *claimsCheck {
		if err := runClaimsCheck(); err != nil {
			fmt.Fprintln(os.Stderr, "claims-check:", err)
			os.Exit(1)
		}
		fmt.Println("claims-check: every load-bearing security claim is stated once and linked elsewhere")
		return
	}
	if *docsLint {
		if err := runDocsLint(); err != nil {
			fmt.Fprintln(os.Stderr, "docs-lint:", err)
			os.Exit(1)
		}
		fmt.Println("docs-lint: every documented `idea` command names a real verb and a resolvable reference")
		return
	}
	if *apiDocs {
		if err := runAPIDocsGenerate(); err != nil {
			fmt.Fprintln(os.Stderr, "api-docs:", err)
			os.Exit(1)
		}
		return
	}
	if *apiDocsCheck {
		if err := runAPIDocsCheck(); err != nil {
			fmt.Fprintln(os.Stderr, "api-docs-check:", err)
			os.Exit(1)
		}
		fmt.Println("api-docs-check: docs/api.md has a row for every route in internal/daemon/routes.go")
		return
	}
	if *apiCheck {
		if err := runAPICheck(); err != nil {
			fmt.Fprintln(os.Stderr, "api-check:", err)
			os.Exit(1)
		}
		// Second axis: paths matching is not the same as the contract matching.
		// api-check proved every route is documented; this proves each handler's
		// request body is, which is the gap `idea verify --fail` shipped through.
		root, err := repoRoot()
		if err != nil {
			fmt.Fprintln(os.Stderr, "api-check:", err)
			os.Exit(1)
		}
		if err := runBodyCheck(filepath.Join(root, routesPkg), filepath.Join(root, specPath)); err != nil {
			fmt.Fprintln(os.Stderr, "api-check:", err)
			os.Exit(1)
		}
		if err := runConflictCheck(filepath.Join(root, routesPkg), filepath.Join(root, specPath)); err != nil {
			fmt.Fprintln(os.Stderr, "api-check:", err)
			os.Exit(1)
		}
		fmt.Println("api-check: docs/openapi.yaml covers every route in internal/daemon/routes.go,")
		fmt.Println("           every handler's request-body fields are documented, and every")
		fmt.Println("           operation that can answer 409 declares one")
		return
	}

	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "docsgen:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	path := filepath.Join(root, "docs", "cli.md")

	current, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	table, err := commandTable()
	if err != nil {
		return err
	}
	want, err := splice(string(current), table)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if want == string(current) {
		return nil
	}
	if check {
		return fmt.Errorf("docs/cli.md is out of date with internal/cli/cli.go; run `make docs` and commit the result")
	}
	return os.WriteFile(path, []byte(want), 0o644)
}

// commandTable renders the markdown table through the CLI's own help command,
// which is the point: the drift check exercises the same code path a user does.
// The table goes to the stdout writer, not to the human help's stderr.
func commandTable() (string, error) {
	var out bytes.Buffer
	if err := cli.Run([]string{"help", "--format=md"}, &out, io.Discard); err != nil {
		return "", err
	}
	if out.Len() == 0 {
		return "", fmt.Errorf("`idea help --format=md` wrote nothing to stdout")
	}
	return out.String(), nil
}

// splice replaces the text between the markers, leaving the surrounding prose
// untouched.
func splice(doc, table string) (string, error) {
	start := strings.Index(doc, beginMarker)
	if start < 0 {
		return "", fmt.Errorf("missing %s", beginMarker)
	}
	end := strings.Index(doc, endMarker)
	if end < 0 {
		return "", fmt.Errorf("missing %s", endMarker)
	}
	if end < start {
		return "", fmt.Errorf("%s appears before %s", endMarker, beginMarker)
	}
	block := beginMarker + "\n" + generatedNote + "\n\n" + table + "\n"
	return doc[:start] + block + doc[end:], nil
}

// repoRoot walks up from the working directory to the module root, so the tool
// works from anywhere rather than only from the directory make happens to use.
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod found above %s", dir)
		}
		dir = parent
	}
}
